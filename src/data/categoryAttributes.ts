export function listingAttributes(
  categoryId: CategoryId | undefined,
  values: Record<string, string> = {},
): Listing["attributes"] {
  return (categoryId ? categoryAttributes[categoryId] : []).flatMap(
    ([label]) => {
      const value = values[label]?.trim();
      return value ? [{ label, value }] : [];
    },
  );
}
